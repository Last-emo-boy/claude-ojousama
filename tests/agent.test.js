'use strict'
const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { EventEmitter } = require('events')
const { Store } = require('../src/main/store')
const { backendId, backendName, sessionForBackend, namespaceSession, codexOptions } = require('../src/main/agent')
const P = require('../src/main/persona')

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ojousama-agent-test-'))
try {
  const fresh = new Store(path.join(dir, 'fresh'))
  assert.equal(fresh.get('settings').backend, process.platform === 'win32' ? 'dsh' : 'codex')
  assert.equal(fresh.get('settings').permission, process.platform === 'win32' ? 'workspace-write' : 'read-only')
  const oldDir = path.join(dir, 'old')
  fs.mkdirSync(oldDir)
  const legacy = { settings: { provider: 'old-provider', model: 'old-model', cwd: 'C:\\work' }, chat: { sessionId: 'dsh-thread', messages: [{ role: 'user', text: 'hello' }] }, todos: [{ id: 't1', text: 'keep me' }] }
  fs.writeFileSync(path.join(oldDir, 'pet-data.json'), JSON.stringify(legacy))
  const old = new Store(oldDir)
  assert.equal(old.get('settings').backend, 'dsh')
  assert.equal(old.get('settings').permission, 'workspace-write')
  assert.equal(old.get('settings').provider, 'old-provider')
  assert.deepEqual(old.get('chat'), legacy.chat)
  assert.deepEqual(old.get('todos'), legacy.todos)
  old.patch('settings', { backend: 'codex', codexModel: 'selected-model' })
  old.flush()
  const reloaded = new Store(oldDir)
  assert.equal(reloaded.get('settings').backend, 'codex')
  assert.equal(reloaded.get('settings').model, 'old-model')
  assert.equal(reloaded.get('settings').codexModel, 'selected-model')

  assert.equal(backendId({}), 'dsh')
  assert.equal(backendName({ backend: 'codex' }), 'Codex')
  assert.equal(sessionForBackend('old-thread', 'dsh'), 'old-thread')
  assert.equal(sessionForBackend('old-thread', 'codex'), null)
  assert.equal(sessionForBackend('codex:new-thread', 'codex'), 'new-thread')
  assert.equal(sessionForBackend('codex:new-thread', 'dsh'), null)
  const run = namespaceSession(new EventEmitter(), 'codex')
  let event, result
  run.on('event', (value) => { event = value })
  run.on('done', (value) => { result = value })
  run.emit('event', { type: 'session', sessionId: 'id' })
  run.emit('done', { ok: true, sessionId: 'id' })
  assert.equal(event.sessionId, 'codex:id')
  assert.equal(result.sessionId, 'codex:id')
  const dsh = namespaceSession(new EventEmitter(), 'dsh')
  dsh.on('done', (value) => assert.equal(value.sessionId, 'legacy-id'))
  dsh.emit('done', { sessionId: 'legacy-id' })

  const settings = { cwd: '/work', permission: 'workspace-write', codexModel: 'chat-model', codexEffort: 'high', codexGlanceModel: 'look-model', codexGlanceEffort: 'low', loadAgentsMd: true, loadSkills: true }
  const full = codexOptions(settings, { prompt: 'hello', persona: 'pet', sessionId: 'codex:id' })
  assert.equal(full.sessionId, 'id')
  assert.equal(full.permission, 'workspace-write')
  assert.equal(full.model, 'chat-model')
  assert.equal(full.loadAgentsMd, true)
  const look = codexOptions(settings, { prompt: 'look', tools: 'look', permission: 'danger-full-access', images: ['/shot.png'] })
  assert.equal(look.permission, 'read-only')
  assert.equal(look.model, 'look-model')
  assert.equal(look.reasoningEffort, 'low')
  assert.equal(look.loadAgentsMd, false)
  assert.equal(look.loadSkills, false)
  assert.deepEqual(look.images, ['/shot.png'])
  assert.equal(codexOptions({}, { prompt: 'scan', tools: 'scan' }).scanRoot, '')

  const glance = { reason: 'user', app: 'editor', title: 'file', imagePath: '/shot.png', ocr: '' }
  assert.match(P.personaPrompt({ backend: 'codex' }), /内核是 Codex/)
  assert.match(P.personaPrompt({}), /内核是 DeepSeek Harness/)
  assert.doesNotMatch(P.glancePrompt({ ...glance, backend: 'codex' }), /read_image/)
  assert.match(P.glancePrompt(glance), /read_image/)
  assert.equal(P.imageReference('/shot.png', 'codex'), '查看随消息附上的屏幕截图。')
  console.log('PASS agent routing, settings migration, model selection and image prompts')
} finally {
  fs.rmSync(dir, { recursive: true, force: true })
}
