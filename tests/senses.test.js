// Unit checks for src/main/senses.js
const S = require('../src/main/senses')
const cases = []
const check = (name, got, want) => cases.push({ name, ok: JSON.stringify(got) === JSON.stringify(want), got, want })

check('traceback', !!S.findError('foo\nTraceback (most recent call last):\n  File "a.py"'), true)
check('py error', !!S.findError('ZeroDivisionError: division by zero'), true)
check('js uncaught', !!S.findError('Uncaught TypeError: x is not a function'), true)
check('npm', !!S.findError('npm ERR! code ELIFECYCLE'), true)
check('ts', !!S.findError('src/a.ts(3,5): error TS2322: Type'), true)
check('cn build', !!S.findError('项目编译失败，请检查'), true)
check('normal code', !!S.findError('throw new Error(msg)\nconst e = new TypeError()\nif (error) return'), false)
check('normal text', !!S.findError('There was no error in the report today'), false)
check('sig stable', S.errorSignature('TypeError: x at line 12') === S.errorSignature('TypeError: x at line 99'), true)

check('clip error', S.classifyClip('Traceback (most recent call last):\n  File "main.py", line 3\nKeyError: name'), 'error')
check('clip code', S.classifyClip('function add(a, b) {\n  return a + b;\n}\nconsole.log(add(1, 2));'), 'code')
check('clip english', S.classifyClip('The quick brown fox jumps over the lazy dog while the cat sleeps quietly.'), 'english')
check('clip token', S.classifyClip('sk' + '-' + 'x'.repeat(36)), null)
check('clip password', S.classifyClip('my password is hunter2 and the token is abc'), null)
check('clip code6', S.classifyClip('482913'), null)
check('clip chinese', S.classifyClip('今天中午吃什么呢我想吃面条还是米饭呢好纠结啊真的'), null)

check('block proc', S.isBlocked({ process: 'KeePassXC', title: 'db' }), true)
check('block title', S.isBlocked({ process: 'msedge', title: 'InPrivate - Edge' }), true)
check('not blocked', S.isBlocked({ process: 'Code', title: 'main.js - VS Code' }), false)
check('custom list', S.isBlocked({ process: 'Code', title: 'secret.txt' }, ['secret']), true)
check('meeting', S.isMeeting({ process: 'wemeetapp', title: '腾讯会议' }), true)
check('distraction', S.isDistraction({ process: 'msedge', title: '哔哩哔哩 (゜-゜)つロ 干杯~' }), '哔哩哔哩')
check('music', S.musicTitle({ title: '晴天 - 周杰伦' }), '晴天 - 周杰伦')
check('music idle', S.musicTitle({ title: '网易云音乐' }), null)

// review round 2: false positives
check('tim vs timer.js', S.isBlocked({ process: 'Code', title: 'timer.js - VS Code' }), false)
check('signal vs signal_handlers', S.isBlocked({ process: 'Code', title: 'signal_handlers.py' }), false)
check('TIM app', S.isBlocked({ process: 'TIM', title: 'TIM' }), true)
check('x.com vs dropbox', S.isDistraction({ process: 'msedge', title: 'Dropbox.com - Files' }), null)
check('x.com real', S.isDistraction({ process: 'msedge', title: 'Home / x.com' }), 'x.com')
check('bilibili url', S.isDistraction({ process: 'chrome', title: 'www.bilibili.com/video' }), 'bilibili')
check('cargo pass', !!S.findError('test result: ok. 12 passed; 0 failed; 0 ignored'), false)
check('cargo fail', !!S.findError('test result: FAILED. 10 passed; 2 failed'), true)
check('meeting notes doc', S.isMeeting({ process: 'msedge', title: 'Meeting notes - Google Docs' }), false)
check('idle meeting app title', S.MEETING_TITLE.test('腾讯会议'), false)
check('in meeting title', S.MEETING_TITLE.test('腾讯会议 - 会议中'), true)
check('seed phrase', S.classifyClip('abandon ability able about above absent absorb abstract absurd abuse access accident'), null)

const bad = cases.filter((c) => !c.ok)
for (const c of bad) console.log('FAIL', c.name, 'got', JSON.stringify(c.got), 'want', JSON.stringify(c.want))
console.log(`${cases.length - bad.length}/${cases.length} passed`)
process.exit(bad.length ? 1 : 0)
