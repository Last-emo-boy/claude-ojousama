'use strict'
const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { replaceApp, desktopQuote } = require('../tools/install-app')
const pkg = require('../package.json')

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ojousama-packaging-test-'))
try {
  const source = path.join(dir, 'source')
  const target = path.join(dir, 'target')
  fs.mkdirSync(source)
  fs.writeFileSync(path.join(source, 'app'), 'version 1')
  replaceApp(source, target, () => true)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 1')
  fs.writeFileSync(path.join(source, 'app'), 'version 2')
  replaceApp(source, target, () => true)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.throws(() => replaceApp(source, target, () => false), /unrelated directory/)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.throws(() => replaceApp(path.join(dir, 'missing'), target, () => true))
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.deepEqual(fs.readdirSync(dir).sort(), ['source', 'target'])
  assert.equal(desktopQuote('/home/a b/app'), '"/home/a b/app"')
  assert.equal(desktopQuote('/home/$name%/app'), '"/home/\\$name%%/app"')
  assert.equal(desktopQuote('/home/a"b/app'), '"/home/a\\"b/app"')
  assert.equal(pkg.build.asar, false)
  assert.equal(pkg.build.mac.identity, null)
  assert.deepEqual(pkg.build.win.target, ['nsis', 'zip'])
  assert.deepEqual(pkg.build.mac.target, ['dmg', 'zip'])
  assert.deepEqual(pkg.build.linux.target, ['AppImage', 'deb'])
  assert.equal(pkg.build.appId, 'com.claude-ojousama.app')
  assert.equal(pkg.build.executableName, undefined)
  assert.equal(pkg.build.win.executableName, 'ClaudeOjousama')
  assert.equal(pkg.build.linux.executableName, 'claude-ojousama')
  assert.ok(pkg.build.deb.depends.includes('python3'))
  const icon = fs.readFileSync(path.join(__dirname, '..', pkg.build.mac.icon))
  assert.ok(icon.readUInt32BE(16) >= 512 && icon.readUInt32BE(20) >= 512)
  console.log('PASS portable packaging targets, user-local install/update, recovery and desktop quoting')
} finally {
  fs.rmSync(dir, { recursive: true, force: true })
}
