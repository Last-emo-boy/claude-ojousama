'use strict'
const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { replaceApp, desktopQuote, installTarget } = require('../tools/install-app')
const { buildOutput, packagePath, builderArguments, deliverArchives } = require('../tools/build-app')
const pkg = require('../package.json')

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ojousama-packaging-test-'))
try {
  const source = path.join(dir, 'source')
  const target = path.join(dir, 'target')
  fs.mkdirSync(source)
  fs.writeFileSync(path.join(source, 'app'), 'version 1')
  replaceApp(source, target, () => true)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 1')
  fs.writeFileSync(path.join(source, 'app'), 'version 2')
  replaceApp(source, target, () => true)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.throws(() => replaceApp(source, target, () => false), /unrelated directory/)
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.throws(() => replaceApp(path.join(dir, 'missing'), target, () => true))
  assert.equal(fs.readFileSync(path.join(target, 'app'), 'utf8'), 'version 2')
  assert.deepEqual(fs.readdirSync(dir).sort(), ['source', 'target'])
  assert.equal(desktopQuote('/home/a b/app'), '"/home/a b/app"')
  assert.equal(desktopQuote('/home/$name%/app'), '"/home/\\$name%%/app"')
  assert.equal(desktopQuote('/home/a"b/app'), '"/home/a\\"b/app"')
  assert.equal(pkg.build.asar, false)
  assert.equal(pkg.build.mac.identity, '-')
  assert.equal(pkg.build.mac.hardenedRuntime, true)
  assert.equal(pkg.build.mac.sign, undefined)
  const entitlements = fs.readFileSync(path.join(__dirname, '..', pkg.build.mac.entitlements), 'utf8')
  assert.match(entitlements, /com\.apple\.security\.cs\.allow-jit/)
  assert.match(entitlements, /com\.apple\.security\.cs\.disable-library-validation/)
  assert.deepEqual(pkg.build.win.target, ['nsis', 'zip'])
  assert.deepEqual(pkg.build.mac.target, ['dmg', 'zip'])
  assert.deepEqual(pkg.build.linux.target, ['AppImage', 'deb'])
  assert.equal(pkg.build.appId, 'com.claude-ojousama.app')
  assert.equal(pkg.build.executableName, undefined)
  assert.equal(pkg.build.win.executableName, 'ClaudeOjousama')
  assert.equal(pkg.build.linux.executableName, 'claude-ojousama')
  assert.ok(pkg.build.deb.depends.includes('python3'))
  const icon = fs.readFileSync(path.join(__dirname, '..', pkg.build.mac.icon))
  assert.ok(icon.readUInt32BE(16) >= 512 && icon.readUInt32BE(20) >= 512)
  // POSIX source installers must preserve relocatable macOS framework links.
  // Windows uses the separate PowerShell installer and has different link privileges.
  if (process.platform !== 'win32') {
    const bundle = path.join(dir, 'bundle')
    const copy = path.join(dir, 'installed-bundle')
    const resources = path.join(bundle, 'Framework.framework', 'Versions', 'A', 'Resources')
    fs.mkdirSync(resources, { recursive: true })
    fs.writeFileSync(path.join(resources, 'icudtl.dat'), 'ICU fixture')
    fs.symlinkSync('A', path.join(bundle, 'Framework.framework', 'Versions', 'Current'))
    fs.symlinkSync('Versions/Current/Resources', path.join(bundle, 'Framework.framework', 'Resources'))
    replaceApp(bundle, copy, () => true)
    assert.equal(fs.readlinkSync(path.join(copy, 'Framework.framework', 'Versions', 'Current')), 'A')
    assert.equal(fs.readlinkSync(path.join(copy, 'Framework.framework', 'Resources')), 'Versions/Current/Resources')
    fs.renameSync(bundle, path.join(dir, 'removed-source'))
    assert.equal(fs.readFileSync(path.join(copy, 'Framework.framework', 'Resources', 'icudtl.dat'), 'utf8'), 'ICU fixture')
  }
  const syncedRoot = path.join(dir, 'synced', 'project')
  const home = path.join(dir, 'home')
  const output = buildOutput({ platform: 'darwin', arch: 'arm64', root: syncedRoot, home })
  assert.equal(output, path.join(home, 'Library', 'Caches', 'claude-ojousama', 'build', 'arm64'))
  assert.equal(output.startsWith(syncedRoot + path.sep), false)
  assert.equal(packagePath(output, { platform: 'darwin', arch: 'arm64' }), path.join(output, 'mac-arm64', 'Claude Ojousama.app'))
  assert.equal(installTarget({ platform: 'darwin', home }), path.join(home, 'Applications', 'Claude Ojousama.app'))
  assert.equal(buildOutput({ platform: 'linux', root: syncedRoot }), path.join(syncedRoot, 'dist'))
  assert.equal(buildOutput({ platform: 'win32', root: syncedRoot }), path.join(syncedRoot, 'dist'))
  assert.ok(builderArguments(output, { dir: true }).includes(`--config.directories.output=${output}`))
  fs.mkdirSync(output, { recursive: true })
  fs.writeFileSync(path.join(output, 'release.dmg'), 'archive')
  fs.writeFileSync(path.join(output, 'release.zip'), 'archive')
  fs.writeFileSync(path.join(output, 'builder-debug.yml'), 'debug')
  fs.mkdirSync(path.join(output, 'NeverCopy.app'))
  const delivered = path.join(syncedRoot, 'dist')
  assert.deepEqual(deliverArchives(output, delivered).sort(), ['release.dmg', 'release.zip'])
  assert.deepEqual(fs.readdirSync(delivered).sort(), ['release.dmg', 'release.zip'])
  console.log('PASS portable packaging targets, user-local install/update, recovery and desktop quoting')
} finally {
  fs.rmSync(dir, { recursive: true, force: true })
}
